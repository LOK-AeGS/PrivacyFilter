// 정규식 토큰 더미 값 템플릿. {i} 자리에 등장 순번(1부터)을 채운다.
// pad(i, n): 0 채움 n 자리. 파이썬 {i:04d} 등과 동일하게 동작.
function pad(i, n) {
  return String(i).padStart(n, "0");
}

